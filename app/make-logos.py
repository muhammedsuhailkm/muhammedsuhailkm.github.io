#!/usr/bin/env python3
"""Regenerates src/logos.ts from the devicon package (MIT licence).

Run after `pnpm install` when a skill in src/data.ts needs a new logo:
    python3 make-logos.py
"""
import base64, pathlib

# skill name in data.ts -> (devicon folder, file variant)
LOGOS = {
    "FastAPI": ("fastapi", "original"),
    "Python": ("python", "original"),
    "TypeScript": ("typescript", "original"),
    "Node.js": ("nodejs", "original"),
    "Express.js": ("express", "original"),
    ".NET": ("dotnetcore", "original"),
    "C#": ("csharp", "original"),
    "C": ("c", "original"),
    "PostgreSQL": ("postgresql", "original"),
    "MySQL": ("mysql", "original"),
    "MSSQL": ("microsoftsqlserver", "original"),
    "MongoDB": ("mongodb", "original"),
    "Next.js": ("nextjs", "original"),
    "React": ("react", "original"),
    "Docker": ("docker", "original"),
}

root = pathlib.Path(__file__).parent
lines = [
    "// Generated by make-logos.py from the devicon package (MIT licence). Do not edit by hand.",
    "",
    "export const logos: Record<string, { src: string }> = {",
]
for name, (folder, variant) in LOGOS.items():
    svg = (root / "node_modules/devicon/icons" / folder / f"{folder}-{variant}.svg").read_bytes()
    uri = "data:image/svg+xml;base64," + base64.b64encode(svg).decode()
    lines.append(f'  {name!r}: {{ src: "{uri}" }},'.replace("'", '"'))
lines.append("}")
(root / "src/logos.ts").write_text("\n".join(lines) + "\n")
print(f"Wrote src/logos.ts with {len(LOGOS)} logos")
